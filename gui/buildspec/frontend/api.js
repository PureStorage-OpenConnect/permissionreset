// Distinct principals of MOCK_DIR_ACES / MOCK_FILE_ACES, plus EVERYONE@ in
// both SACLs when sacl is set, as speccapture's IdentityReport counts them.
function mockIdentity(verified, sacl) {
  const both = 'directory DACL, file DACL';
  return {
    special: 3,
    named: 1,
    numericUser: 1,
    numericGroup: 0,
    sacl: { special: sacl ? 1 : 0, named: 0, numericUser: 0, numericGroup: 0 },
    principals: [
      { who: 'OWNER@', group: false, kind: 'special', where: both },
      { who: 'GROUP@', group: false, kind: 'special', where: both },
      { who: 'storage-admins@testdrive.local', group: true, kind: 'named', where: both },
      { who: '10010', group: false, kind: 'numeric user', where: both },
      { who: 'EVERYONE@', group: false, kind: 'special', where: both + (sacl ? ', directory SACL, file SACL' : '') },
    ],
    verified: !!verified,
  };
}

function reversedError() {
  return new Error(
    'capture: file exemplar\n"/data/templates/readme.md" is a directory; both\n' +
      'arguments are directories -- expected\n(directory, file)\n\n' +
      '  Mark a regular file for the second slot.\n' +
      '  Symlinks, FIFOs and device nodes are refused.'
  );
}

function mountError() {
  return new Error(
    'mount /mnt/fb is not NFSv4.1: options\n' +
      '"rw,vers=4.0,rsize=1048576,hard,proto=tcp" do not\n' +
      'contain vers=4.1 or minorversion=1\n\n' +
      '  remount with vers=4.1, or use the userspace\n' +
      '  transport, which speaks NFSv4.1 directly.'
  );
}

function replayError() {
  return new Error(
    '--verify-write: probe SETACL rejected\n' +
      '  probe:  /data/scratch/.build-spec-a91f/dir\n' +
      '  ace:    "A:fd:1610612737:rwaDxtTcCoy"\n' +
      '  status: NFS4ERR_BADOWNER\n\n' +
      'This identity was created by SMB and has no\n' +
      'replayable NFSv4 form. No spec file was created.\n' +
      'build-spec will not guess a replacement uid.'
  );
}

function mockApi() {
  let session = null; // {transport, mountPath}

  function captureLike(dir, file, verified, withDacl) {
    if (session && session.transport === 'kernel' && (session.mountPath || '').indexOf('41') < 0) {
      return Promise.reject(mountError());
    }
    if (/\/archive$/.test(dir) && /\/readme\.md$/.test(file)) {
      return Promise.reject(reversedError());
    }
    if (verified && /legacy-smb\.dat$/.test(file)) {
      return Promise.reject(replayError());
    }
    if (/\/ediscovery\//.test(dir) && /\/exhibit\.pdf$/.test(file)) {
      return delay(350).then(() => ({
        yaml: mockSaclYaml(!!withDacl),
        dirAces: MOCK_DIR_ACES.slice(),
        fileAces: MOCK_FILE_ACES.slice(),
        dirSacl: MOCK_DIR_SACL.slice(),
        fileSacl: MOCK_FILE_SACL.slice(),
        hasSacl: true,
        keepsDacl: !withDacl,
        notes: withDacl
          ? ['captured 2 audit (U) ACE(s) as sacl: alongside the DACL (--with-dacl); applying this spec replaces every object\'s DACL']
          : ['captured 2 audit (U) ACE(s); the spec keeps each object\'s own DACL and replaces only its SACL'],
        identity: mockIdentity(verified, true),
      }));
    }
    return delay(350).then(() => ({
      yaml: mockYaml(),
      dirAces: MOCK_DIR_ACES.slice(),
      fileAces: MOCK_FILE_ACES.slice(),
      identity: mockIdentity(verified),
    }));
  }

  return {
    capabilities: () =>
      delay(80).then(() => ({
        os: 'darwin',
        kernelTransport: true,
        credentialFromProcess: true,
        version: '0.9.2-mock',
      })),
    connect: (req) => {
      fireBusy('connecting');
      return delay(300).then(() => {
        fireBusy('');
        session = { transport: req.transport, mountPath: req.mountPath };
        return { root: '/data', warnings: [] };
      });
    },
    exports: () => delay(150).then(() => ({ exports: MOCK_EXPORTS.slice(), supported: true })),
    listDir: (path, limit) => {
      fireBusy('listing');
      return delay(200).then(() => {
        fireBusy('');
        const entries = MOCK_TREE[path] || [];
        const truncated = typeof limit === 'number' && entries.length > limit;
        return { entries: truncated ? entries.slice(0, limit) : entries, truncated };
      });
    },
    capture: (dir, file, withDacl) => {
      fireBusy('capturing');
      return captureLike(dir, file, false, withDacl).finally(() => fireBusy(''));
    },
    verify: (scratch, dir, file, withDacl) => {
      fireBusy('verifying');
      return captureLike(dir, file, true, withDacl).finally(() => fireBusy(''));
    },
    saclPlan: () => delay(200).then(() => ({ ...MOCK_PLAN })),
    savePlan: (json, suggestedName) => delay(150).then(() => ({ path: '/Users/mock/specs/' + suggestedName })),
    saveSpec: (yaml, suggestedName) => {
      fireBusy('saving');
      return delay(250).then(() => {
        fireBusy('');
        return { path: '/Users/mock/specs/' + suggestedName };
      });
    },
    chooseScratch: () => delay(150).then(() => ({ path: '/mnt/fb/scratch' })),
    disconnect: () => {
      session = null;
      return delay(80).then(() => ({}));
    },
    openRunbook: () => {
      // eslint-disable-next-line no-console
      console.log('(mock) would open runbook in browser');
    },
  };
}

export const api = hasGo && !forceMock ? realApi() : mockApi();
export const isMock = !(hasGo && !forceMock);

export function onSessionLost(cb) {
  sessionLostHandlers.push(cb);
}
export function onBusy(cb) {
  busyHandlers.push(cb);
}
