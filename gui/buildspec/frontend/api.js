// api.js — thin adapter over window.go.main.App.* (Wails v2 bindings).
// When window.go is absent (plain-browser preview) or ?mock=1 is present,
// falls back to an in-memory mock so the page renders and every scenario
// (idle / captured / captured-with-sacl / sacl-plan / err-mount /
// err-reversed / err-non-replayable) is
// reachable for visual review without a Go backend.

const params = new URLSearchParams(location.search);
const forceMock = params.get('mock') === '1';
const hasGo = !!(window.go && window.go.main && window.go.main.App);

let sessionLostHandlers = [];
let busyHandlers = [];

function fireSessionLost(reason) {
  for (const cb of sessionLostHandlers) cb(reason);
}
function fireBusy(phase) {
  for (const cb of busyHandlers) cb(phase);
}

// ---------------------------------------------------------------------
// Real (Wails) transport
// ---------------------------------------------------------------------

function realApi() {
  const App = window.go.main.App;
  if (window.runtime && window.runtime.EventsOn) {
    window.runtime.EventsOn('session:lost', (reason) => fireSessionLost(reason));
    window.runtime.EventsOn('busy', (phase) => fireBusy(phase));
  }
  return {
    capabilities: () => App.Capabilities(),
    connect: (req) => App.Connect(req),
    exports: () => App.Exports(),
    listDir: (path, limit) => App.ListDir(path, limit),
    capture: (dir, file, withDacl, acceptUnproven) => App.Capture(dir, file, !!withDacl, !!acceptUnproven),
    verify: (scratch, dir, file, withDacl) => App.Verify(scratch, dir, file, !!withDacl),
    saveSpec: (yaml, suggestedName) => App.SaveSpec(yaml, suggestedName),
    saclPlan: () => App.SaclPlan(),
    savePlan: (json, suggestedName) => App.SavePlan(json, suggestedName),
    chooseScratch: () => App.ChooseScratch(),
    disconnect: () => App.Disconnect(),
    openRunbook: () => {
      if (window.runtime && window.runtime.BrowserOpenURL) {
        window.runtime.BrowserOpenURL(
          'https://github.com/PureStorage-OpenConnect/permissionreset/blob/main/docs/field-preview/runbook.md'
        );
      }
    },
  };
}

