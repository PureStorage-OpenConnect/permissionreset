function mockYaml() {
  const dirLines = MOCK_DIR_ACES.map((a) => `      - "${a}"`).join('\n');
  const fileLines = MOCK_FILE_ACES.map((a) => `      - "${a}"`).join('\n');
  return (
    `# build-spec capture -- generated by permissionreset build-spec\n` +
    `# type: file also matches FIFO, socket, and device nodes; exclude by name\n` +
    `# if the file exemplar's ACL is not appropriate for them.\n` +
    `protocol: nfsv4\n` +
    `default: {}\n` +
    `rules:\n` +
    `  - match:\n` +
    `      type: directory\n` +
    `    acl:\n${dirLines}\n` +
    `  - match:\n` +
    `      type: file\n` +
    `    acl:\n${fileLines}\n`
  );
}

// The ediscovery exemplars carry audit (U) ACEs, so the SACL views are
// reachable in the mock: a DACL-keeping spec by default, acl: + sacl: with
// withDacl.
const MOCK_DIR_SACL = ['U:fdS:EVERYONE@:wadD'];
const MOCK_FILE_SACL = ['U:SF:EVERYONE@:rwadDxtTcCoy'];

function mockSaclYaml(withDacl) {
  const rule = (type, acl, sacl) =>
    `  - match:\n      type: ${type}\n` +
    (withDacl ? `    acl:\n${acl.map((a) => `      - "${a}"`).join('\n')}\n` : '') +
    `    sacl:\n${sacl.map((a) => `      - "${a}"`).join('\n')}\n`;
  return (
    `# build-spec capture -- generated by permissionreset build-spec\n` +
    (withDacl ? '' : `# sacl:-only rules: each object keeps its own DACL; apply with permissionreset --sacl\n`) +
    `protocol: nfsv4\n` +
    `default: {}\n` +
    `rules:\n` +
    rule('directory', MOCK_DIR_ACES, MOCK_DIR_SACL) +
    rule('file', MOCK_FILE_ACES, MOCK_FILE_SACL)
  );
}

